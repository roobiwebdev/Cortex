#!/usr/bin/env bash
# Writes apps/desktop/THIRD_PARTY_RUST.md: every third-party Rust crate in the
# macOS desktop build, with its version and licence. Run it after Cargo.lock
# changes and commit the result. See docs/engineering/desktop.md (Licensing).
#
# Needs cargo (rustup on PATH) and jq. Reads Cargo.lock with --locked, so it
# never changes the lockfile.
#
# This list names licences but does not carry their texts. For a release build
# that ships full texts, install cargo-about (`cargo install --locked cargo-about`),
# add an about.toml with the accepted licences and an about.hbs template, then run
# `cargo about generate about.hbs > apps/desktop/THIRD_PARTY_LICENSES.html`.
set -euo pipefail

root="$(cd "$(dirname "$0")/../.." && pwd)"
out="$root/apps/desktop/THIRD_PARTY_RUST.md"
platform="${PLATFORM:-aarch64-apple-darwin}"

command -v jq >/dev/null || { echo "jq is required (brew install jq)" >&2; exit 1; }

metadata="$(cargo metadata --format-version 1 --locked --filter-platform "$platform" \
  --manifest-path "$root/Cargo.toml")"

{
  echo "# Third-party Rust crates"
  echo
  echo "Generated by \`scripts/desktop/third-party-licenses.sh\` for \`$platform\`. Do not edit by hand."
  echo "Workspace crates are left out. Rec and apple-cryptokit-rs are credited in the root \`NOTICE\`."
  echo
  echo "| Crate | Version | Licence |"
  echo "| ----- | ------- | ------- |"
  # Only packages that the resolver actually uses on this platform, minus our own workspace members.
  jq -r '
    (.workspace_members) as $ws
    | ([.resolve.nodes[].id]) as $used
    | .packages[]
    | select(.id as $id | ($used | index($id)) and (($ws | index($id)) | not))
    | [.name, .version, (.license // ("see " + (.license_file // "crate")))]
    | "| \(.[0]) | \(.[1]) | \(.[2] | gsub("\\|"; "\\\\|")) |"
  ' <<<"$metadata" | sort -f -u
} >"$out"

echo "wrote $out ($(($(grep -c '^| ' "$out") - 2)) crates)"
