//! The single IPC checkpoint (engineering plan §6): every command the webview
//! can call and every event it can hear is declared here. TypeScript bindings
//! are generated from this module into `apps/desktop/src/ipc/bindings.ts`
//! (run `pnpm --filter desktop ipc:bindings`). Windows may only call commands
//! their capability grants (see `build.rs` and `capabilities/default.json`).

use serde::{Deserialize, Serialize};
use specta::Type;
use tauri::{AppHandle, State};
use tauri_specta::{Event, collect_commands, collect_events};

use crate::engine::{EngineState, EngineStatus, RecorderSettings, StubEngine};

/// Full engine snapshot, emitted on every change.
#[derive(Debug, Clone, Serialize, Deserialize, Type)]
pub struct EngineStateEvent(pub EngineState);

impl Event for EngineStateEvent {
    const NAME: &'static str = "engine://state";
}

/// Applies a change, broadcasts the new state, and returns it to the caller.
fn commit(app: &AppHandle, engine: &StubEngine, f: impl FnOnce(&mut EngineState)) -> EngineState {
    let next = engine.apply(f);
    broadcast(app, next.clone());
    next
}

pub fn broadcast(app: &AppHandle, state: EngineState) {
    if let Err(err) = EngineStateEvent(state).emit(app) {
        eprintln!("cortex: failed to emit engine state: {err}");
    }
}

#[tauri::command]
#[specta::specta]
fn engine_state(engine: State<'_, StubEngine>) -> EngineState {
    engine.snapshot()
}

/// Stub: skips the countdown and starts "recording" immediately.
#[tauri::command]
#[specta::specta]
fn engine_start(app: AppHandle, engine: State<'_, StubEngine>) -> EngineState {
    commit(&app, &engine, |s| {
        if s.status == EngineStatus::Idle {
            s.status = EngineStatus::Recording;
            s.countdown_left = 0;
            s.elapsed_secs = 0.0;
            s.bytes_written = 0.0;
            s.dropped_frames = 0;
        }
    })
}

/// Stub: returns to idle without writing a file.
#[tauri::command]
#[specta::specta]
fn engine_stop(app: AppHandle, engine: State<'_, StubEngine>) -> EngineState {
    commit(&app, &engine, |s| {
        if matches!(
            s.status,
            EngineStatus::Recording | EngineStatus::Paused | EngineStatus::Countdown
        ) {
            s.status = EngineStatus::Idle;
            s.countdown_left = 0;
        }
    })
}

#[tauri::command]
#[specta::specta]
fn engine_pause(app: AppHandle, engine: State<'_, StubEngine>) -> EngineState {
    commit(&app, &engine, |s| {
        if s.status == EngineStatus::Recording {
            s.status = EngineStatus::Paused;
        }
    })
}

#[tauri::command]
#[specta::specta]
fn engine_resume(app: AppHandle, engine: State<'_, StubEngine>) -> EngineState {
    commit(&app, &engine, |s| {
        if s.status == EngineStatus::Paused {
            s.status = EngineStatus::Recording;
        }
    })
}

/// Replaces the settings wholesale (the UI merges its patch first). Stub: kept
/// in memory only; the real engine validates ranges and persists atomically.
#[tauri::command]
#[specta::specta]
fn update_settings(
    app: AppHandle,
    engine: State<'_, StubEngine>,
    settings: RecorderSettings,
) -> EngineState {
    commit(&app, &engine, |s| s.settings = settings)
}

/// The command + event registry shared by the app and the bindings exporter.
pub fn builder() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            engine_state,
            engine_start,
            engine_stop,
            engine_pause,
            engine_resume,
            update_settings,
        ])
        .events(collect_events![EngineStateEvent])
        // serde_json writes NaN/Infinity as `null`, so floats default to `number | null`.
        // The engine only ever emits finite values (and rejects non-finite input), so the
        // bindings type floats as plain `number`.
        .semantic_types(
            specta_typescript::semantic::Configuration::empty().enable_lossless_floats(),
        )
}

