/**
 * SOURCE OF TRUTH KEYWORDS: formatClock, formatBytes, formatAgo, time format, size format
 * WHAT:  Display formatting for recording clocks, file sizes and relative dates.
 * WHY:   Clocks and sizes appear on many surfaces and must read identically.
 * WHERE: record bar, HUD, menu-bar panel, toasts, trim window, recordings list.
 */
export function formatClock(totalSecs: number) {
  const secs = Math.max(0, Math.floor(totalSecs));
  const h = Math.floor(secs / 3600);
  const m = Math.floor((secs % 3600) / 60);
  const s = secs % 60;
  const mm = String(m).padStart(2, "0");
  const ss = String(s).padStart(2, "0");
  return h > 0 ? `${h}:${mm}:${ss}` : `${mm}:${ss}`;
}

export function formatBytes(bytes: number) {
  if (bytes >= 1e9) return `${(bytes / 1e9).toFixed(1)} GB`;
  if (bytes >= 1e6) return `${Math.round(bytes / 1e6)} MB`;
  return `${Math.max(1, Math.round(bytes / 1e3))} KB`;
}

export function formatAgo(ms: number, now = Date.now()) {
  const mins = Math.round((now - ms) / 60000);
  if (mins < 1) return "Just now";
  if (mins < 60) return `${mins} min ago`;
  const hours = Math.round(mins / 60);
  if (hours < 24) return `${hours} h ago`;
  const days = Math.round(hours / 24);
  return days === 1 ? "Yesterday" : `${days} days ago`;
}
